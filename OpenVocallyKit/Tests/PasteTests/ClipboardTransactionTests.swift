import Foundation
import Testing

@testable import Paste

struct ClipboardTransactionTests {
  private let richItem = PasteboardItemSnapshot(representations: [
    PasteboardRepresentation(type: "public.rtf", data: Data("{\\rtf1 bold}".utf8)),
    PasteboardRepresentation(type: "public.html", data: Data("<b>bold</b>".utf8)),
    PasteboardRepresentation(type: "public.utf8-plain-text", data: Data("bold".utf8)),
  ])
  private let imageItem = PasteboardItemSnapshot(representations: [
    PasteboardRepresentation(type: "public.png", data: Data([0x89, 0x50, 0x4E, 0x47, 0x00, 0xFF]))
  ])

  @Test func `every item and type of the previous clipboard is restored byte for byte`() {
    let board = FakePasteboard(items: [richItem, imageItem])
    let transaction = ClipboardTransaction.begin(on: board, writing: "hello")
    #expect(transaction.restore(on: board) == .restored)
    #expect(board.items == [richItem, imageItem])
    #expect(board.writes.last?.currentHostOnly == true)
  }

  @Test func `a concealed clipboard is left empty, not rewritten`() {
    let password = item(("public.utf8-plain-text", "hunter2"), ("org.nspasteboard.ConcealedType", ""))
    let board = FakePasteboard(items: [password])
    let transaction = ClipboardTransaction.begin(on: board, writing: "hello")
    #expect(transaction.restore(on: board) == .restored)
    #expect(board.items == [])
    #expect(board.writes.last?.currentHostOnly == true)
  }

  @Test func `the write is the text marked transient and auto-generated, on this host only`() {
    let board = FakePasteboard(items: [richItem])
    _ = ClipboardTransaction.begin(on: board, writing: "hello")
    #expect(
      board.items == [
        item(
          ("public.utf8-plain-text", "hello"), ("org.nspasteboard.TransientType", ""),
          ("org.nspasteboard.AutoGeneratedType", ""))
      ])
    #expect(board.writes.last?.currentHostOnly == true)
  }

  @Test func `restore is skipped when someone copied after us`() {
    let board = FakePasteboard(items: [richItem])
    let transaction = ClipboardTransaction.begin(on: board, writing: "hello")
    board.userCopies("other")
    #expect(transaction.restore(on: board) == .skippedBecauseChanged)
    #expect(board.items == [item(("public.utf8-plain-text", "other"))])
  }

  @Test func `a rewrite moves ownership to the new change count`() {
    let board = FakePasteboard(items: [richItem])
    var transaction = ClipboardTransaction.begin(on: board, writing: "hello")
    let first = transaction.ownedChangeCount
    let rewrote = transaction.rewrite(on: board)
    #expect(rewrote)
    #expect(transaction.ownedChangeCount == first + 1)
    #expect(transaction.restore(on: board) == .restored)
    #expect(board.items == [richItem])
  }

  @Test func `a rewrite after someone copied writes nothing`() {
    let board = FakePasteboard(items: [richItem])
    var transaction = ClipboardTransaction.begin(on: board, writing: "hello")
    board.userCopies("other")
    let rewrote = transaction.rewrite(on: board)
    #expect(!rewrote)
    #expect(board.items == [item(("public.utf8-plain-text", "other"))])
  }

  @Test func `an empty previous clipboard is restored as empty`() {
    let board = FakePasteboard(items: [])
    let transaction = ClipboardTransaction.begin(on: board, writing: "hello")
    #expect(transaction.restore(on: board) == .restored)
    #expect(board.items == [])
  }
}
