import Foundation

struct PasteboardRepresentation: Sendable, Equatable {
  let type: String
  let data: Data
}

/// One pasteboard item with every type it offered, in the order it offered them.
struct PasteboardItemSnapshot: Sendable, Equatable {
  var representations: [PasteboardRepresentation]
}

protocol Pasteboard: Sendable {
  var changeCount: Int { get }
  /// Types whose data cannot be read, such as a lazy promise that fails, are skipped.
  func readItems() -> [PasteboardItemSnapshot]
  /// Clears the board, writes `items` as separate items and returns the new change count.
  /// `currentHostOnly` keeps the write off Universal Clipboard.
  func replace(with items: [PasteboardItemSnapshot], currentHostOnly: Bool) -> Int
}

enum PasteboardMarker {
  /// nspasteboard.org: clipboard managers do not record the item.
  static let transient = "org.nspasteboard.TransientType"
  /// nspasteboard.org: written by software, not by a user copy.
  static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
  /// nspasteboard.org: a secret, such as a password, that its owner clears on its own.
  static let concealed = "org.nspasteboard.ConcealedType"
  static let plainText = "public.utf8-plain-text"
}

/// The saved clipboard and the change count of our own write. The restore runs only while
/// that count is current, so anything copied after us wins.
struct ClipboardTransaction: Sendable {
  enum RestoreResult: Sendable, Equatable {
    case restored
    case skippedBecauseChanged
  }

  let saved: [PasteboardItemSnapshot]
  private(set) var ownedChangeCount: Int
  private let text: String

  static func begin(on pasteboard: some Pasteboard, writing text: String) -> ClipboardTransaction {
    let saved = pasteboard.readItems()
    let count = pasteboard.replace(with: [ownedItem(text)], currentHostOnly: true)
    return ClipboardTransaction(saved: saved, ownedChangeCount: count, text: text)
  }

  /// Retry: writes the text again and owns the new change count. False, writing
  /// nothing, when someone copied since our write: their copy wins.
  mutating func rewrite(on pasteboard: some Pasteboard) -> Bool {
    guard isCurrent(on: pasteboard) else { return false }
    ownedChangeCount = pasteboard.replace(with: [Self.ownedItem(text)], currentHostOnly: true)
    return true
  }

  /// True while the clipboard still holds our write.
  func isCurrent(on pasteboard: some Pasteboard) -> Bool {
    pasteboard.changeCount == ownedChangeCount
  }

  /// Restores the user's items exactly as they were, on this host only; an empty clipboard is
  /// restored as empty. A concealed clipboard is left empty instead: rewriting it
  /// would give it a change count its owner, such as a password manager, no longer clears.
  func restore(on pasteboard: some Pasteboard) -> RestoreResult {
    guard isCurrent(on: pasteboard) else { return .skippedBecauseChanged }
    _ = pasteboard.replace(with: savedIsSecret ? [] : saved, currentHostOnly: true)
    return .restored
  }

  private var savedIsSecret: Bool {
    saved.contains { item in
      item.representations.contains { $0.type == PasteboardMarker.concealed }
    }
  }

  static func ownedItem(_ text: String) -> PasteboardItemSnapshot {
    PasteboardItemSnapshot(representations: [
      PasteboardRepresentation(type: PasteboardMarker.plainText, data: Data(text.utf8)),
      PasteboardRepresentation(type: PasteboardMarker.transient, data: Data()),
      PasteboardRepresentation(type: PasteboardMarker.autoGenerated, data: Data()),
    ])
  }
}
