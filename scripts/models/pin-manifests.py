#!/usr/bin/env python3
"""Write OpenVocallyKit/Sources/Models/ModelManifests.swift.

Each model is pinned to a Hugging Face commit. Sizes and SHA-256 come from the Hub's
LFS metadata; small files that are not in LFS are downloaded and hashed.

Usage: scripts/models/pin-manifests.py

Run it after changing a revision below, then commit the regenerated file.
"""

import hashlib
import json
import sys
import os
import subprocess

HUB = "https://huggingface.co"
OUTPUT = "OpenVocallyKit/Sources/Models/ModelManifests.swift"

PARAKEET_FILES = [
    "Preprocessor.mlmodelc",
    "Encoder.mlmodelc",
    "Decoder.mlmodelc",
    "JointDecisionv3.mlmodelc",
    "parakeet_vocab.json",
]
MODELS = [
    ("parakeetV3", "FluidInference/parakeet-tdt-0.6b-v3-coreml",
     "7dd20fe6b1797d35f5e3307e8b1732d9a178edfe", PARAKEET_FILES, "parakeet-tdt-0.6b-v3/"),
    ("parakeetUltra", "FluidInference/parakeet-ultra-coreml",
     "95eaa59a39d4394f047a4dc5cce480388a60d1b6", PARAKEET_FILES, "parakeet-ultra/"),
    ("whisperTurbo", "ggerganov/whisper.cpp",
     "5359861c739e955e79d9a303bcbc70fb988958b1", ["ggml-large-v3-turbo.bin"], ""),
]


def fetch(url):
    return subprocess.run(["curl", "-fsSL", url], check=True, capture_output=True).stdout


def entries(repo, revision, path):
    url = f"{HUB}/api/models/{repo}/tree/{revision}/{path}?recursive=1&expand=1"
    return [e for e in json.loads(fetch(url)) if e["type"] == "file"]


def entry(repo, revision, path):
    parent, _, name = path.rpartition("/")
    url = f"{HUB}/api/models/{repo}/tree/{revision}/{parent}?expand=1"
    return next(e for e in json.loads(fetch(url)) if e["path"] == path)


def pinned(repo, revision, e):
    lfs = e.get("lfs")
    if lfs:
        return e["path"], lfs["size"], lfs["oid"]
    body = fetch(f"{HUB}/{repo}/resolve/{revision}/{e['path']}")
    assert len(body) == e["size"], e["path"]
    return e["path"], len(body), hashlib.sha256(body).hexdigest()


def files(repo, revision, names):
    for name in names:
        if name.endswith(".mlmodelc"):
            found = entries(repo, revision, name)
        else:
            found = [entry(repo, revision, name)]
        for e in sorted(found, key=lambda e: e["path"]):
            yield pinned(repo, revision, e)


def swift():
    yield "// Generated by scripts/models/pin-manifests.py. Do not edit."
    yield ""
    yield "extension ModelManifest {"
    for name, repo, revision, names, prefix in MODELS:
        yield f"  static let {name} = ModelManifest("
        yield f"    repository: \"{repo}\","
        yield f"    revision: \"{revision}\","
        yield f"    localPrefix: \"{prefix}\","
        yield "    files: ["
        for path, size, sha in files(repo, revision, names):
            yield f"      ModelFile(path: \"{path}\", size: {size}, sha256: \"{sha}\"),"
        yield "    ]"
        yield "  )"
    yield "}"


def main():
    if len(sys.argv) > 1:
        print(__doc__.strip())
        return
    os.chdir(os.path.join(os.path.dirname(__file__), "..", ".."))
    with open(OUTPUT, "w") as output:
        output.write("\n".join(swift()) + "\n")
    subprocess.run(["swift", "format", "format", "--in-place", OUTPUT], check=True)


main()
